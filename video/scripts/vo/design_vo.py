#!/usr/bin/env python3
"""Builds the designed v5 timing map, video/src/data/vo5_design.json, from scripts/vo/script5.json. No audio is made.
place_take.py lays a recorded take onto these beats and writes the map the film plays, data/vo5.json.

A phrase either comes from v4 ({from, i}): it keeps its exact v4 frames and word times, so the locked close-ups
and the typed tagline don't move. Or it is new ({caption, at, dur}): its start and length were designed against
the picture, and its words split the phrase by syllable weight like make_vo.py (the last word a little longer, as
people stretch the end of a phrase). Each line is laid out like a file with 0.2 s of silence at each end and carries
`at`, its speech start on the film clock, which the timeline places it by. The ElevenLabs takes replace these
estimates later (fit_takes.py lays them on these frames; align_vo.py can re-time the film to them).

  python3 video/scripts/vo/design_vo.py
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "src")
PAD = 0.2
SPOKEN = {"16th": 3, "ai": 2, "4000": 3, "16": 2, "7": 2, "3": 1, "1": 1}   # as make_vo.py


def syllables(word):
    k = re.sub(r"[^a-z0-9]", "", word.lower())
    if k in SPOKEN:
        return SPOKEN[k]
    w = re.sub(r"[^a-z]", "", word.lower())
    n = len(re.findall(r"[aeiouy]+", w)) if w else 1
    if w.endswith("e") and not w.endswith(("le", "ee")) and n > 1:
        n -= 1
    return max(1, n)


def v4_offsets():
    """Film-clock offset of each v4 line (its file time + offset = film time), from film4/timeline.ts."""
    tl = open(os.path.join(SRC, "film4", "timeline.ts")).read()
    bar = float(re.search(r"bar: ([\d.]+)", tl).group(1))
    T = {k: 0.0 if e == "0" else float(e[2:-1]) * bar for k, e in re.findall(r"(\w+): (B\([\d.]+\)|0)", tl.split("export const T = {")[1].split("};")[0])}
    vo4 = json.load(open(os.path.join(SRC, "data", "vo4.json")))["lines"]
    out = {}
    for lid, expr in re.findall(r'place\(\{ id: "(F\d+)", at: ([^}]+?) \}\)', tl):
        for k in sorted(T, key=len, reverse=True):
            expr = expr.replace("T." + k, repr(T[k]))
        out[lid] = eval(expr) - vo4[lid]["speechStart"]
    return vo4, out


def main():
    spec = json.load(open(os.path.join(HERE, "script5.json")))["lines"]
    vo4, off4 = v4_offsets()
    lines = {}
    for lid, line in spec.items():
        film = []   # phrases on the film clock
        for p in line["phrases"]:
            if "from" in p:
                q, o = vo4[p["from"]]["phrases"][p["i"]], off4[p["from"]]
                film.append({"text": q["text"], "start": q["start"] + o, "end": q["end"] + o, "key": q["key"],
                             "words": [{"w": w["w"], "start": w["start"] + o, "end": w["end"] + o} for w in q["words"]]})
            else:
                words = p["caption"].split()
                wt = [syllables(w) * (1.3 if i == len(words) - 1 else 1.0) for i, w in enumerate(words)]
                b = [p["at"] + p["dur"] * sum(wt[:i]) / sum(wt) for i in range(len(words) + 1)]
                film.append({"text": p["caption"], "start": p["at"], "end": p["at"] + p["dur"], "key": p.get("key", []),
                             "words": [{"w": w, "start": b[i], "end": b[i + 1]} for i, w in enumerate(words)]})
        at = film[0]["start"]
        f = lambda t: round(t - at + PAD, 3)   # film clock → line file clock
        phrases = [{"text": q["text"], "start": f(q["start"]), "end": f(q["end"]), "key": q["key"],
                    "words": [{"w": w["w"], "start": f(w["start"]), "end": f(w["end"])} for w in q["words"]]} for q in film]
        lines[lid] = {"file": f"vo/{lid}.wav", "at": round(at, 3), "duration": round(phrases[-1]["end"] + PAD, 3),
                      "speechStart": PAD, "speechEnd": phrases[-1]["end"], "phrases": phrases}
    ids = list(lines)
    for a, b in zip(ids, ids[1:]):
        end, nxt = lines[a]["at"] + lines[a]["speechEnd"] - PAD, lines[b]["at"]
        assert end <= nxt, f"{a} runs into {b} ({end:.2f} > {nxt:.2f})"
    out = os.path.join(SRC, "data", "vo5_design.json")
    json.dump({"$doc": "Generated by video/scripts/vo/design_vo.py from scripts/vo/script5.json (v5 Keeper script): the designed beats, before any recording. Times in seconds from the start of a line laid out with 0.2 s of silence at each end; `at` is the line's speech start on the film clock.", "lines": lines}, open(out, "w"), indent=1, ensure_ascii=False)
    print(f"{len(lines)} lines, {sum(len(l['phrases']) for l in lines.values())} phrases → {os.path.relpath(out)}")


if __name__ == "__main__":
    main()

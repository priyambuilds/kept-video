"""Re-times the film to whatever VO is in audio/vo/ (the placeholder WAVs or the final ElevenLabs MP3s).

For each line in script.json it finds audio/vo/<ID>.wav|.mp3 (L03a/L03b can also come as one L03 file),
transcribes it with faster-whisper (word timestamps), aligns the recognised words to the caption words,
and writes video/src/data/vo.json, which the captions, the Keeper's speech beats and the scene timing
all read. Unmatched words are interpolated between their matched neighbours, so a misheard word never
breaks the caption timing.

  ~/.cache/kept/tts/bin/python video/scripts/vo/align_vo.py
"""
import difflib, json, os, re, sys
import numpy as np, librosa
from faster_whisper import WhisperModel

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
VO = os.path.join(ROOT, "audio", "vo")
OUT = os.path.join(ROOT, "video", "src", "data", os.environ.get("VO_MAP", "vo.json"))
os.environ.setdefault("HF_HOME", os.path.expanduser("~/.cache/kept/hf"))

norm = lambda w: re.sub(r"[^a-z0-9]", "", w.lower().replace("16th", "sixteenth").replace("ai", "ai"))


def find(lid):
    for ext in (".wav", ".mp3", ".m4a"):
        p = os.path.join(VO, lid + ext)
        if os.path.exists(p):
            return p
    return None


def align(model, path, phrases):
    y, sr = librosa.load(path, sr=16000, mono=True)
    dur = len(y) / sr
    segs, _ = model.transcribe(y, word_timestamps=True, beam_size=5)
    heard = [(norm(w.word), w.start, w.end) for s in segs for w in s.words if norm(w.word)]
    cap = [(pi, w) for pi, p in enumerate(phrases) for w in p["caption"].split()]
    starts, ends = [None] * len(cap), [None] * len(cap)
    sm = difflib.SequenceMatcher(a=[norm(w) for _, w in cap], b=[h[0] for h in heard], autojunk=False)
    for a, b, n in sm.get_matching_blocks():
        for i in range(n):
            starts[a + i], ends[a + i] = heard[b + i][1], heard[b + i][2]
    # Speech bounds from energy, for the ends of the line when ASR misses them.
    iv = librosa.effects.split(y, top_db=35)
    s0, s1 = (iv[0][0] / sr, iv[-1][1] / sr) if len(iv) else (0.0, dur)
    if starts[0] is None:
        starts[0] = s0
    if ends[-1] is None:
        ends[-1] = s1
    known = [i for i, v in enumerate(starts) if v is not None]
    for i in range(len(cap)):   # interpolate unmatched words between matched neighbours
        if starts[i] is None:
            lo = max(k for k in known if k < i); hi = min([k for k in known if k > i] or [len(cap) - 1])
            t0, t1 = ends[lo] or starts[lo], starts[hi] if hi != i else s1
            starts[i] = t0 + (t1 - t0) * (i - lo) / max(1, hi - lo)
    for i in range(len(cap)):
        if ends[i] is None:
            ends[i] = starts[i + 1] if i + 1 < len(cap) else s1
    out = []
    for pi, p in enumerate(phrases):
        idx = [i for i, (q, _) in enumerate(cap) if q == pi]
        out.append({"text": p["caption"], "start": round(starts[idx[0]], 3), "end": round(ends[idx[-1]], 3), "key": p.get("key", []),
                    "words": [{"w": cap[i][1], "start": round(starts[i], 3), "end": round(ends[i], 3)} for i in idx]})
    matched = sum(1 for a, b, n in sm.get_matching_blocks() for _ in range(n))
    return dur, out, matched, len(cap)


def main():
    spec = json.load(open(os.path.join(os.path.dirname(__file__), os.environ.get("VO_SCRIPT", "script.json"))))
    model = WhisperModel("base.en", device="cpu", compute_type="int8")
    result = {"$doc": "Generated by video/scripts/vo/align_vo.py from the files in audio/vo/. Times in seconds from the start of `file`, plus `offset` when two IDs share one file.", "lines": {}}
    lines = {k: [dict(p, caption=p.get("caption", p["text"])) for p in v["phrases"]] for k, v in spec["lines"].items()}
    done = set()
    for lid, phrases in lines.items():
        if lid in done:
            continue
        path, group = find(lid), [lid]
        if not path and lid in ("L03a", "L03b"):   # one L03 file holding both halves
            path, group = find("L03"), ["L03a", "L03b"]
        if not path:
            print(f"{lid}: no file, skipped"); continue
        allp = [p for g in group for p in lines[g]]
        dur, out, ok, n = align(model, path, allp)
        i = 0
        for g in group:
            ph = out[i:i + len(lines[g])]; i += len(lines[g])
            result["lines"][g] = {"file": os.path.relpath(path, os.path.join(ROOT, "audio")), "duration": round(dur, 3),
                                  "speechStart": ph[0]["start"], "speechEnd": ph[-1]["end"], "phrases": ph}
            done.add(g)
        print(f"{'+'.join(group)}: {os.path.basename(path)} {dur:.2f}s · {ok}/{n} words matched")
    old = json.load(open(OUT))["lines"] if os.path.exists(OUT) else {}
    for lid, l in result["lines"].items():   # v5 maps place each line by its film time (`at`): keep it
        if "at" in old.get(lid, {}):
            l["at"] = old[lid]["at"]
    json.dump(result, open(OUT, "w"), indent=1, ensure_ascii=False)
    print("wrote", OUT)


if __name__ == "__main__":
    sys.exit(main())

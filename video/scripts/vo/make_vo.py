"""Synthesises the Keeper's VO (audio/vo/*.wav) and its timing map (video/src/data/vo.json).

Voice: Kokoro-82M (Apache-2.0) via kokoro-onnx, voice `am_onyx` (the deepest, flattest of the stock
male voices; measured f0 median 88 Hz), then pitched down 1.5 semitones and treated for a dry, gravelly,
close read (EQ, de-ess, compression, light saturation). Each phrase is synthesised alone and joined with
designed gaps so the comic beats are exact. Words get times by syllable weight inside each phrase,
snapped to the phrase's internal energy dips; captions only need word-level accuracy to a frame or two.

Run (see video/README.md):
  ~/.cache/kept/tts/bin/python video/scripts/vo/make_vo.py
espeak-ng (used by kokoro's phonemiser) fails on long install paths, so the venv lives in ~/.cache/kept.
"""
import json, os, re, subprocess, sys, tempfile
import numpy as np, soundfile as sf, librosa
from kokoro_onnx import Kokoro

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
MODELS = os.path.expanduser("~/.cache/kept/models")
OUT_DIR = os.path.join(ROOT, "audio", "vo")
MAP_OUT = os.path.join(ROOT, "video", "src", "data", os.environ.get("VO_MAP", "vo.json"))  # read by src/data/vo.ts
SR_TTS, SR_OUT = 24000, 48000
PAD = 0.2           # silence at each end of a line file (audio/vo/README.md)
PITCH = -1.5        # semitones, whole voice
TARGET_LUFS = -18.0

CHAIN = ",".join([
    "highpass=f=70",
    "equalizer=f=115:t=q:w=1:g=2.5",     # chest
    "equalizer=f=320:t=q:w=1.2:g=-2",    # mud
    "equalizer=f=3000:t=q:w=1:g=2",      # presence for phone speakers
    "deesser=i=0.4",
    "acompressor=threshold=-22dB:ratio=3.5:attack=4:release=90:makeup=3dB",
    "volume=5dB,asoftclip=type=atan,volume=-5dB",   # a little grit
])


def ffmpeg(args):
    subprocess.run(["ffmpeg", "-v", "error", "-y", *args], check=True)


def pitch_shift(x, sr, semis):
    """Resample-style shift (formants move with pitch: a bigger, darker body), duration preserved."""
    if abs(semis) < 1e-6:
        return x
    r = 2 ** (semis / 12)
    with tempfile.TemporaryDirectory() as d:
        a, b = os.path.join(d, "a.wav"), os.path.join(d, "b.wav")
        sf.write(a, x, sr, subtype="FLOAT")
        ffmpeg(["-i", a, "-af", f"asetrate={sr * r:.3f},aresample={sr},atempo={1 / r:.6f}", b])
        y, _ = sf.read(b, dtype="float32")
    return y


def trim(a, sr):
    """Cut Kokoro's breathy tail (it sits 30–38 dB down and adds ~0.3 s per phrase), keeping 15 ms
    before the first sound and 80 ms after the last, with a short fade so final consonants survive."""
    _, (s, e) = librosa.effects.trim(a, top_db=34, frame_length=512, hop_length=64)
    s, e = max(0, s - int(0.015 * sr)), min(len(a), e + int(0.08 * sr))
    a = a[s:e].copy()
    f = int(0.03 * sr)
    a[-f:] *= np.linspace(1, 0, f, dtype=np.float32)
    return a


SPOKEN = {"16th": 3, "ai": 2, "4000": 3, "16": 2, "7": 2, "3": 1, "1": 1}   # caption tokens whose letters don't show how they're said


def syllables(word):
    if re.sub(r"[^a-z0-9]", "", word.lower()) in SPOKEN:
        return SPOKEN[re.sub(r"[^a-z0-9]", "", word.lower())]
    w = re.sub(r"[^a-z]", "", word.lower())
    if not w:
        return 1
    n = len(re.findall(r"[aeiouy]+", w))
    if w.endswith("e") and not w.endswith(("le", "ee")) and n > 1:
        n -= 1
    return max(1, n)


def word_times(x, sr, words, t0):
    """Word start/end inside one phrase clip: syllable-weighted, snapped to low-energy dips."""
    dur = len(x) / sr
    w = np.array([syllables(v) for v in words], float)
    bounds = np.concatenate([[0], np.cumsum(w) / w.sum()]) * dur
    hop = int(sr * 0.005)
    rms = librosa.feature.rms(y=x, frame_length=hop * 4, hop_length=hop)[0]
    for i in range(1, len(bounds) - 1):   # snap each inner boundary to the quietest point within ±60 ms
        c = int(bounds[i] / 0.005)
        lo, hi = max(0, c - 12), min(len(rms) - 1, c + 12)
        if hi > lo:
            bounds[i] = (lo + int(np.argmin(rms[lo:hi]))) * 0.005
    return [{"w": v, "start": round(t0 + bounds[i], 3), "end": round(t0 + bounds[i + 1], 3)} for i, v in enumerate(words)]


def lufs(x, sr):
    import pyloudnorm as pyln
    return pyln.Meter(sr).integrated_loudness(x)


def main():
    spec = json.load(open(os.path.join(os.path.dirname(__file__), os.environ.get("VO_SCRIPT", "script.json"))))
    k = Kokoro(os.path.join(MODELS, "kokoro-v1.0.onnx"), os.path.join(MODELS, "voices-v1.0.bin"))
    os.makedirs(OUT_DIR, exist_ok=True)
    timing = {"$doc": "Generated by video/scripts/vo/make_vo.py. Times in seconds from the start of audio/vo/<id>.wav (which has 0.2 s of silence at each end).", "voice": spec["voice"], "lines": {}}
    for lid, line in spec["lines"].items():
        parts, phrases, t = [], [], PAD
        parts.append(np.zeros(int(PAD * SR_TTS), np.float32))
        for ph in line["phrases"]:
            gap = ph.get("gap", 0.0)
            if gap and phrases:
                parts.append(np.zeros(int(gap * SR_TTS), np.float32)); t += gap
            a, sr = k.create(ph["text"], voice=spec["voice"], speed=ph.get("speed", spec["defaultSpeed"]), lang=spec["lang"])
            a = trim(a.astype(np.float32), sr)
            a = pitch_shift(a, sr, ph.get("pitch", 0.0))
            a *= 10 ** (ph.get("gain", 0) / 20)
            cap = ph.get("caption", ph["text"])
            words = cap.split()
            phrases.append({"text": cap, "start": round(t, 3), "end": round(t + len(a) / sr, 3), "key": ph.get("key", []), "words": word_times(a, sr, words, t)})
            parts.append(a); t += len(a) / sr
        parts.append(np.zeros(int(PAD * SR_TTS), np.float32))
        raw = np.concatenate(parts)
        # Placeholder only: squeeze a take that overruns its SHOTLIST window (the ElevenLabs read is
        # recorded to the slot sheet instead). Phrase and word times scale with it.
        speech = phrases[-1]["end"] - phrases[0]["start"]
        tempo = max(1.0, speech / line["fit"]) if line.get("fit") else 1.0
        if tempo > 1.0:
            body = raw[int(PAD * SR_TTS):len(raw) - int(PAD * SR_TTS)]
            with tempfile.TemporaryDirectory() as d:
                a, b = os.path.join(d, "a.wav"), os.path.join(d, "b.wav")
                sf.write(a, body, SR_TTS, subtype="FLOAT")
                ffmpeg(["-i", a, "-af", f"atempo={tempo:.5f}", b])
                body, _ = sf.read(b, dtype="float32")
            pad = np.zeros(int(PAD * SR_TTS), np.float32)
            raw = np.concatenate([pad, body, pad])
            sc = lambda v: round(PAD + (v - PAD) / tempo, 3)
            for p in phrases:
                p["start"], p["end"] = sc(p["start"]), sc(p["end"])
                for w in p["words"]:
                    w["start"], w["end"] = sc(w["start"]), sc(w["end"])
        with tempfile.TemporaryDirectory() as d:
            src, dst = os.path.join(d, "raw.wav"), os.path.join(d, "out.wav")
            sf.write(src, raw, SR_TTS, subtype="FLOAT")
            r = 2 ** (PITCH / 12)
            ffmpeg(["-i", src, "-af", f"asetrate={SR_TTS * r:.3f},aresample={SR_OUT},atempo={1 / r:.6f},{CHAIN}", "-ac", "1", dst])
            y, _ = sf.read(dst, dtype="float32")
        # One loudness for every line; quieter lines (gain < 0 in the script) keep their offset.
        line_gain = min(ph.get("gain", 0) for ph in line["phrases"])
        y *= 10 ** ((TARGET_LUFS + line_gain - lufs(y, SR_OUT)) / 20)
        peak = np.max(np.abs(y))
        if peak > 10 ** (-1.5 / 20):
            y *= 10 ** (-1.5 / 20) / peak
        sf.write(os.path.join(OUT_DIR, f"{lid}.wav"), y, SR_OUT, subtype="PCM_24")
        dur = len(y) / SR_OUT
        timing["lines"][lid] = {"file": f"vo/{lid}.wav", "duration": round(dur, 3), "speechStart": phrases[0]["start"], "speechEnd": phrases[-1]["end"], "phrases": phrases}
        nw = sum(len(p["words"]) for p in phrases)
        print(f"{lid}: x{tempo:.2f} {dur:5.2f}s file · speech {phrases[-1]['end'] - phrases[0]['start']:4.2f}s · {nw} words · {nw / (phrases[-1]['end'] - phrases[0]['start']):.2f} w/s")
    os.makedirs(os.path.dirname(MAP_OUT), exist_ok=True)
    json.dump(timing, open(MAP_OUT, "w"), indent=1)
    print("wrote", MAP_OUT)


if __name__ == "__main__":
    sys.exit(main())

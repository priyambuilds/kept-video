// design/assets/icons/*.svg (MDI, 24×24, one path each) → src/ui/icons.gen.ts, so icons are inline
// vector paths (crisp at any scale, colourable) instead of image masks.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const dir = join(ROOT, "design/assets/icons");
const out = {};
for (const f of readdirSync(dir).filter((f) => f.endsWith(".svg"))) {
  const m = readFileSync(join(dir, f), "utf8").match(/<path d="([^"]+)"/);
  if (m) out[f.replace(/^icon-|\.svg$/g, "")] = m[1];
}
writeFileSync(join(ROOT, "video/src/ui/icons.gen.ts"), `// Generated by scripts/gen-icons.mjs from design/assets/icons (Pictogrammers MDI, Apache-2.0).\nexport const ICONS: Record<string, string> = ${JSON.stringify(out, null, 0)};\n`);
console.log(Object.keys(out).length, "icons");
